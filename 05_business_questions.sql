Section 1 – Customer Overview
Business Objective;
********************************
Before diving into detailed analysis, management wants answers to four high-level questions:
1.	How many customers do we have?
2.	How many customers are still active?
3.	How many customers have churned?
4.	What is the overall churn rate?
These are the KPIs that would appear at the top of an executive dashboard.

___________________________________________
Section 2 – Customer Demographics Analysis
Business Objective;
*******************************************
Management wants to understand the composition of its customer base and identify whether certain demographic groups are more likely to churn.
We'll analyze:
1.	Gender distribution
2.	Senior Citizen status
3.	Partner status
4.	Dependents status

For each category, we'll answer:
•	How many customers belong to each group?
•	What percentage of customers does each group represent?
•	What is the churn rate within each group?

________________________________________
Section 3 – Customer Services Analysis
Business Objective;
****************************************
Management wants to understand how subscribed services influence customer retention.
We'll answer these questions:
1.	Which Internet Service has the highest churn?
2.	Does Online Security reduce churn?
3.	Does Online Backup affect churn?
4.	Does Device Protection reduce churn?
5.	Does Tech Support improve customer retention?
6.	Do Streaming services influence churn?

